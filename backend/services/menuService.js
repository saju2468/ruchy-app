// Generic restaurant menu builder for any restaurant ID
export function buildSwiggyMenuResponse(resId, restaurantInfo, customCategories = null) {
  const categoriesToUse = customCategories || realNarmadaMenu.categories;

  // Format into Swiggy's groupedCard structure
  const swiggyCards = [
    {
      card: {
        card: {
          "@type": "type.googleapis.com/swiggy.presentation.food.v2.Restaurant",
          info: {
            id: String(resId),
            name: restaurantInfo?.name || "Ruchy Partner Restaurant",
            city: restaurantInfo?.city || "Bangalore",
            cuisines: restaurantInfo?.cuisines || ["North Indian", "South Indian", "Biryani"],
            avgRating: restaurantInfo?.avgRating || "4.3",
            totalRatingsString: restaurantInfo?.totalRatingsString || "5K+",
            costForTwo: restaurantInfo?.costForTwo || "₹400 for two",
            cloudinaryImageId:
              restaurantInfo?.cloudinaryImageId ||
              "RX_THUMBNAIL/IMAGES/VENDOR/2025/11/29/753d7fd4-a3f2-46d0-b803-4e1682b33109_537139.jpg",
            areaName: restaurantInfo?.areaName || restaurantInfo?.locality || "Bangalore",
            locality: restaurantInfo?.locality || "Bangalore",
            sla: restaurantInfo?.sla || {
              slaString: "25-30 mins",
            },
          },
        },
      },
    },
    {
      groupedCard: {
        cardGroupMap: {
          REGULAR: {
            cards: categoriesToUse.map((cat) => ({
              card: {
                card: {
                  "@type":
                    "type.googleapis.com/swiggy.presentation.food.v2.ItemCategory",
                  title: cat.title,
                  itemCards: cat.items.map((item) => ({
                    card: {
                      info: {
                        id: item.id || `${resId}_${Math.random().toString(36).substring(2, 8)}`,
                        name: item.name,
                        price: item.price,
                        defaultPrice: item.price,
                        description: item.description,
                        isVeg: item.isVeg,
                        imageId: item.imageId,
                        ribbon: item.ribbon,
                      },
                    },
                  })),
                },
              },
            })),
          },
        },
      },
    },
  ];

  return {
    statusCode: 0,
    data: {
      statusMessage: "done successfully",
      cards: swiggyCards,
    },
  };
}
